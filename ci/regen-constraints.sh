#!/usr/bin/env bash
# Regenerate a constraints file inside the base image it governs:
#   ci/regen-constraints.sh notebooks [--upgrade]   # constraints.txt (root)
#   ci/regen-constraints.sh ngshare [--upgrade]     # ngshare-notebook/constraints.txt
#   ci/regen-constraints.sh r-studio [--upgrade]    # r-studio/constraints.txt
# Run from anywhere; needs Docker. The base image is read from the
# Dockerfile's BASE_CONTAINER pin and the JupyterHub version from
# JUPYTERHUB_PINS.env, so this is what to run after either changes (the
# base-image-updates workflow runs it for you).
#
# Existing pins are kept wherever they still resolve, so a run moves only
# what the base or a changed requirement forces. --upgrade instead resolves
# every package to its newest release.
#
# notebooks: compiled in the scipy-notebook base (the superset of what the
# notebook images install) after the jupyterhub-singleuser downgrade, with
# the base's installed versions as constraints, so the pins never move a
# package the base already ships. ALLOW_MOVE lists the exceptions; keep it
# in sync with ci/check_constraints.py.
set -euo pipefail

TARGET="${1:?usage: regen-constraints.sh notebooks|ngshare|r-studio [--upgrade]}"
case "${2:-}" in
  "") UPGRADE="" ;;
  --upgrade) UPGRADE="--upgrade" ;;
  *) echo "usage: regen-constraints.sh notebooks|ngshare|r-studio [--upgrade]" >&2; exit 2 ;;
esac
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
. "$ROOT/JUPYTERHUB_PINS.env"
: "${JUPYTERHUB_VERSION:?missing in JUPYTERHUB_PINS.env}"

# otter-grader 7 needs wrapt<2 while the docker-stacks bases ship wrapt 2.x.
ALLOW_MOVE="wrapt"
export JUPYTERHUB_VERSION ALLOW_MOVE UPGRADE

base_of() {
  sed -n 's/^ARG BASE_CONTAINER=//p' "$ROOT/$1/Dockerfile" | head -1
}

body="$(mktemp)"
trap 'rm -f "$body"' EXIT

case "$TARGET" in
notebooks)
  BASE="$(base_of scipy-notebook)"
  OUT="$ROOT/constraints.txt"
  docker run --rm -i --entrypoint bash -v "$ROOT:/repo:ro" \
      -e JUPYTERHUB_VERSION -e ALLOW_MOVE -e UPGRADE "$BASE" -s > "$body" <<'INNER'
set -euo pipefail
mamba install -q -y "jupyterhub-singleuser=${JUPYTERHUB_VERSION}" >/dev/null
pip list --format=freeze | grep -ivE "^($(tr ' ' '|' <<<"$ALLOW_MOVE"))==" > /tmp/base.txt
# otter-grader>=7 keeps pip-compile from backtracking otter to 5.x to
# satisfy the base's wrapt 2.x instead of moving wrapt.
printf -- '-c /tmp/base.txt\notter-grader>=7\n' > /tmp/req.in
cat /repo/requirements.txt /repo/scipy-notebook/requirements.txt >> /tmp/req.in
awk '/^pip install/{f=1} f{print} f&&!/\\$/{f=0}' /repo/install-common.sh \
  | sed 's/^pip install --no-cache-dir//; s/\\//' >> /tmp/req.in
pip install -q pip-tools >/dev/null
# pip-compile keeps the pins already in its output file when they still fit.
cp /repo/constraints.txt /tmp/constraints.txt
pip-compile -q --no-header --no-annotate --strip-extras $UPGRADE -o /tmp/constraints.txt /tmp/req.in
cat /tmp/constraints.txt
INNER
  {
    cat <<EOF
# Shared pip constraints for the notebook images, passed as
# PIP_CONSTRAINT=/tmp/common/constraints.txt per-RUN in the Dockerfiles (not
# a persistent ENV -- it doesn't reach student pods) so install-common.sh
# and each image's requirements.txt resolve against the same pins.
#
# Generated by ci/regen-constraints.sh notebooks -- don't edit by hand.
# Compiled inside $BASE
# after the jupyterhub-singleuser ${JUPYTERHUB_VERSION} downgrade, covering
# requirements.txt, scipy-notebook/requirements.txt and install-common.sh's
# packages (including --with-nbgrader). The base's installed versions are
# constraints, so pins never move a package the base ships, except:
# ${ALLOW_MOVE} (otter-grader 7 needs wrapt<2). ngshare_exchange resolves to
# 0.5.2 because 0.5.3 caps jupyter-core<4.11.2.
EOF
    cat "$body"
  } > "$OUT"
  ;;
ngshare)
  BASE="$(base_of ngshare-notebook)"
  OUT="$ROOT/ngshare-notebook/constraints.txt"
  docker run --rm -i --entrypoint bash -v "$ROOT:/repo:ro" \
      -e JUPYTERHUB_VERSION -e UPGRADE "$BASE" -s > "$body" <<'INNER'
set -euo pipefail
cp /repo/ngshare-notebook/requirements.txt /tmp/req.in
printf 'jupyterhub==%s\n' "$JUPYTERHUB_VERSION" >> /tmp/req.in
pip install -q pip-tools >/dev/null 2>&1
cp /repo/ngshare-notebook/constraints.txt /tmp/constraints.txt
pip-compile -q --no-header --no-annotate --strip-extras $UPGRADE -o /tmp/constraints.txt /tmp/req.in
cat /tmp/constraints.txt
INNER
  {
    cat <<EOF
# Pip constraints for ngshare-notebook, exported as PIP_CONSTRAINT in the
# Dockerfile so requirements.txt's direct deps (plus jupyterhub, pinned in
# JUPYTERHUB_PINS.env) resolve against the same full transitive closure on
# every build.
#
# Generated by ci/regen-constraints.sh ngshare -- don't edit by hand.
# Compiled inside $BASE
# from ngshare-notebook/requirements.txt and jupyterhub==${JUPYTERHUB_VERSION}.
EOF
    cat "$body"
  } > "$OUT"
  ;;
r-studio)
  BASE="$(base_of r-studio)"
  OUT="$ROOT/r-studio/constraints.txt"
  docker run --rm -i --entrypoint bash -v "$ROOT:/repo:ro" \
      -e JUPYTERHUB_VERSION -e UPGRADE "$BASE" -s > "$body" <<'INNER'
set -euo pipefail
# The image installs into the base's system Python after the Dockerfile's
# apt step; do the same, and keep the Python packages apt installed fixed
# (pip can't replace them: they have no RECORD file). pip-tools runs from a
# venv on the same interpreter.
apt-get update -qq && apt-get install -y -qq --no-install-recommends \
  python3 python3-pip python3-venv >/dev/null
python3 -m pip list --format=freeze 2>/dev/null > /tmp/base.txt
python3 -m venv /tmp/piptools && /tmp/piptools/bin/pip install -q pip-tools >/dev/null
printf -- '-c /tmp/base.txt\n' > /tmp/req.in
cat /repo/r-studio/requirements.txt >> /tmp/req.in
printf 'jupyterhub==%s\n' "$JUPYTERHUB_VERSION" >> /tmp/req.in
if [ -f /repo/r-studio/constraints.txt ]; then
  cp /repo/r-studio/constraints.txt /tmp/constraints.txt
fi
/tmp/piptools/bin/pip-compile -q --no-header --no-annotate --strip-extras $UPGRADE -o /tmp/constraints.txt /tmp/req.in
cat /tmp/constraints.txt
INNER
  {
    cat <<EOF
# Pip constraints for r-studio, passed as PIP_CONSTRAINT in the Dockerfile so
# requirements.txt's direct deps (plus jupyterhub, pinned in
# JUPYTERHUB_PINS.env) resolve against the same full transitive closure on
# every build.
#
# Generated by ci/regen-constraints.sh r-studio -- don't edit by hand.
# Compiled inside $BASE
# from r-studio/requirements.txt and jupyterhub==${JUPYTERHUB_VERSION}.
EOF
    cat "$body"
  } > "$OUT"
  ;;
*)
  echo "usage: regen-constraints.sh notebooks|ngshare|r-studio [--upgrade]" >&2
  exit 2
  ;;
esac

echo "wrote ${OUT#"$ROOT"/} ($(grep -c '==' "$OUT") pins) from $BASE"
